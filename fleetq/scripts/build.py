#!/usr/bin/env python3
"""Assemble the stdlib-only single-file artifacts (§11).

* ``build/fq-node`` = ``fleetq/bundles.py`` + ``fleetq/shim/fq_node.py``
* ``bin/fq``        = ``fleetq/bundles.py`` + ``fleetq/client.py``
* ``build/fq.1``    = the man page, rendered from ``bin/fq``'s own argument parser

The build is reproducible: the same sources give byte-identical output, and
each artifact records a digest of its inputs, so a node or client can report
exactly which code it runs. ``--check`` fails if a committed artifact is stale.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "fleetq"

ARTIFACTS = {
    ROOT / "build" / "fq-node": [SRC / "bundles.py", SRC / "shim" / "fq_node.py"],
    ROOT / "bin" / "fq": [SRC / "bundles.py", SRC / "client.py"],
}


def _strip(text: str) -> str:
    out = []
    for line in text.splitlines():
        if line.strip() == "from __future__ import annotations":
            continue
        out.append(line)
    return "\n".join(out) + "\n"


def assemble(parts: list[Path]) -> str:
    body = "".join(f"\n# ---- {p.relative_to(ROOT)} " + "-" * 40 + "\n" + _strip(p.read_text()) for p in parts)
    digest = hashlib.sha256(body.encode()).hexdigest()[:16]
    return (
        "#!/usr/bin/env python3\n"
        f"# Generated by scripts/build.py from {', '.join(str(p.relative_to(ROOT)) for p in parts)}.\n"
        "# Do not edit; edit the sources and rebuild.\n"
        "from __future__ import annotations\n"
        f"BUILD_DIGEST = {digest!r}\n"
        + body
        + "\nif __name__ == '__main__':\n    import sys as _sys\n    _sys.exit(main())\n"
    )


MAN_PAGE = ROOT / "build" / "fq.1"


def _roff(text: str) -> str:
    text = text.replace("%%", "%").replace("\\", "\\e").replace("-", "\\-")
    return "\n".join("\\&" + line if line.startswith((".", "'")) else line for line in text.split("\n"))


def render_man(fq_source: str) -> str:
    """``man fq``: the same parser ``fq --help`` prints, so the two cannot disagree."""
    import argparse

    import types

    module = types.ModuleType("_fq_man")
    sys.modules[module.__name__] = module      # dataclasses look their module up here
    try:
        exec(compile(fq_source, "bin/fq", "exec"), module.__dict__)  # our own build output
    finally:
        del sys.modules[module.__name__]
    parser = module.build_parser()
    version = module.CLIENT_VERSION
    out = [f'.TH FQ 1 "" "fq {version}" "fleetq"', ".SH NAME", "fq \\- " + _roff(parser.description.rstrip(".")),
           ".SH SYNOPSIS", ".B fq", "[\\-\\-json] \\fICOMMAND\\fR [\\fIoptions\\fR] [\\-\\- \\fIjob command\\fR ...]",
           ".SH COMMANDS"]
    commands = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    seen: set[int] = set()
    for name, sub in commands.choices.items():
        if id(sub) in seen:
            continue
        seen.add(id(sub))
        aliases = [n for n, p in commands.choices.items() if p is sub and n != name]
        out += [f'.SS "fq {name}' + (f' ({", ".join(aliases)})' if aliases else "") + '"',
                _roff(sub.description or ""), ".PP", ".nf",
                _roff(sub.format_usage().removeprefix("usage: ").strip()), ".fi"]
        for action in sub._actions:
            if isinstance(action, argparse._HelpAction) or action.help == argparse.SUPPRESS:
                continue
            if action.option_strings:
                label = ", ".join(f"\\fB{_roff(o)}\\fR" for o in action.option_strings)
                if action.nargs != 0:
                    label += f" \\fI{action.metavar or action.dest.upper()}\\fR"
            else:
                label = f"\\fI{action.metavar or action.dest}\\fR"
            if action.choices and not isinstance(action.choices, dict):
                label += " {" + ",".join(action.choices) + "}"
            out += [".TP", label, _roff(action.help or "")]
        if sub.epilog:
            out += [".PP", ".nf", _roff(sub.epilog.strip()), ".fi"]
    for block in parser.epilog.strip().split("\n\n"):
        head, _, body = block.partition("\n")
        if head.endswith(":") or ":" in head and head.split(":")[0].endswith(")"):
            title = head.split(" (")[0].rstrip(":").upper()
            out += [f'.SH "{title}"', ".nf", _roff(body), ".fi"]
        else:
            out += [".SH NOTES", _roff(block)]
    out += [".SH SEE ALSO", "fleetctl help, fleetqd(1) \\- the daemon's own --help, fleetq/README.md"]
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    if all(p.exists() for p in ARTIFACTS[ROOT / "bin" / "fq"]):
        man = render_man(assemble(ARTIFACTS[ROOT / "bin" / "fq"]))
        if check:
            if not MAN_PAGE.exists() or MAN_PAGE.read_text() != man:
                stale.append(str(MAN_PAGE.relative_to(ROOT)))
        else:
            MAN_PAGE.parent.mkdir(parents=True, exist_ok=True)
            MAN_PAGE.write_text(man)
            print(f"built {MAN_PAGE.relative_to(ROOT)}")
    for target, parts in ARTIFACTS.items():
        if not all(p.exists() for p in parts):
            continue
        text = assemble(parts)
        if check:
            if not target.exists() or target.read_text() != text:
                stale.append(str(target.relative_to(ROOT)))
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
        target.chmod(0o755)
        print(f"built {target.relative_to(ROOT)}")
    if stale:
        print("stale artifacts (run scripts/build.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
